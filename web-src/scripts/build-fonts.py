#!/usr/bin/env python3
"""Generate the MCSight Sans web font subset from a full Noto Sans SC VF.

Plan C keeps Noto's design for common Chinese, but ships one WOFF2 per weight
instead of the 98 unicode-range slices generated by Google Fonts. Characters
outside the subset fall back to the system CJK font via the CSS font stack.

The full source font is intentionally not committed. Point the script at a
local Noto Sans SC variable font:

    python -m pip install fonttools brotli
    python web-src/scripts/build-fonts.py --font /path/to/NotoSansSC-VF.ttf
    npm --prefix web-src run build

On Windows the default path is C:/Windows/Fonts/NotoSansSC-VF.ttf when it
exists. The generated WOFF2 files live under web-src/src/assets/fonts/ and are
ignored by git; only views/config/assets/ (Vite output) is committed.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "web-src"
FONT_OUT = WEB / "src" / "assets" / "fonts"
CSS_OUT = WEB / "src" / "styles" / "fonts.css"
FAMILY = "MCSight Sans"
WEIGHTS = ((400, "Regular"), (500, "Medium"), (600, "SemiBold"), (700, "Bold"))
STYLE_BY_WEIGHT = dict(WEIGHTS)

TEXT_EXTS = {".vue", ".ts", ".js", ".css", ".json", ".md", ".html", ".py"}
CJK_RE = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]")


def gb2312_level1() -> set[str]:
    """The 3755 most common GB2312 Hanzi (level 1)."""
    chars: set[str] = set()
    for high in range(0xB0, 0xD8):
        for low in range(0xA1, 0xFF):
            try:
                chars.add(bytes((high, low)).decode("gb2312"))
            except UnicodeDecodeError:
                pass
    return chars


def project_cjk() -> set[str]:
    """Chinese actually used by the UI, backend messages, and tests."""
    paths = list((WEB / "src").rglob("*"))
    paths += list(ROOT.glob("*.py"))
    for folder in ("web", "commands", "config", "utils", "features"):
        paths += list((ROOT / folder).rglob("*.py"))
    built_js = ROOT / "views" / "config" / "assets" / "app.js"
    if built_js.is_file():
        paths.append(built_js)

    chars: set[str] = set()
    for path in paths:
        if not path.is_file() or path.suffix.lower() not in TEXT_EXTS:
            continue
        if "node_modules" in path.parts or ".scratch" in path.parts:
            continue
        chars.update(CJK_RE.findall(path.read_text(encoding="utf-8", errors="ignore")))
    return chars


def charset() -> str:
    """UI text + common Hanzi + Latin, punctuation, and common symbols."""
    chars: set[str] = set()
    chars.update(chr(c) for c in range(0x20, 0x7F))       # ASCII
    chars.update(chr(c) for c in range(0xA0, 0x100))      # Latin-1
    chars.update(chr(c) for c in range(0x2000, 0x2070))   # General punctuation
    chars.update(chr(c) for c in range(0x2190, 0x2200))   # Arrows
    chars.update(chr(c) for c in range(0x25A0, 0x2600))   # Geometric shapes
    chars.update(chr(c) for c in range(0x3000, 0x3040))   # CJK punctuation
    chars.update(chr(c) for c in range(0xFF00, 0xFFF0))   # Fullwidth forms
    chars.update(gb2312_level1())
    chars.update(project_cjk())
    # Whitespace controls are not glyphs; a plain space is kept for metrics.
    chars = {c for c in chars if c == " " or not c.isspace()}
    return "".join(sorted(chars))


def parse_faces(css: str) -> list[dict]:
    """Collect the Manrope/IBM source slices still referenced by fonts.css."""
    blocks = re.findall(r"@font-face\s*\{[^}]*\}", css, flags=re.S)
    faces: list[dict] = []
    for block in blocks:
        family_match = re.search(r"font-family:\s*([^;]+);", block)
        weight_match = re.search(r"font-weight:\s*(\d+);", block)
        src_match = re.search(r"url\(([^)]+)\)", block)
        if not (family_match and weight_match and src_match):
            continue
        family = family_match.group(1).strip().strip("'\"")
        if family not in {"Manrope", "IBM Plex Mono"}:
            continue
        faces.append({
            "family": family,
            "weight": int(weight_match.group(1)),
            "src": Path(src_match.group(1)).name,
        })
    if not faces:
        raise SystemExit(f"no Manrope/IBM @font-face blocks found in {CSS_OUT}")
    return faces


def rename_family(font, family: str, style: str, weight: int) -> None:
    name = font["name"]
    # Keep copyright/license records; replace names that identify the source.
    name.names = [record for record in name.names if record.nameID not in {1, 2, 3, 4, 6, 16, 17}]
    full = f"{family} {style}"
    postscript_family = family.replace(" ", "")
    postscript = f"{postscript_family}-{style}"
    values = {
        1: family,
        2: style,
        3: f"{family}-{style}-subset",
        4: full,
        6: postscript,
        16: family,
        17: style,
    }
    for name_id, value in values.items():
        for platform, encoding, language in ((3, 1, 0x409), (3, 1, 0x804), (0, 3, 0), (0, 4, 0)):
            name.setName(value, name_id, platform, encoding, language)
    name.setName("Version 1.000; MCSight font subset", 5, 3, 1, 0x409)

    os2 = font["OS/2"]
    os2.usWeightClass = weight
    os2.fsSelection &= ~(0x20 | 0x40)
    if weight == 700:
        os2.fsSelection |= 0x20
    elif weight == 400:
        os2.fsSelection |= 0x40
    font["head"].macStyle = (font["head"].macStyle & ~1) | (1 if weight == 700 else 0)


def build_weight(source: Path, weight: int, style: str, text: str) -> Path:
    from fontTools.subset import Options, Subsetter
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont

    font = TTFont(source, lazy=False)
    instantiateVariableFont(font, {"wght": weight}, inplace=True, updateFontNames=False)

    options = Options()
    options.layout_features = ["kern", "liga", "clig", "calt", "locl"]
    options.name_IDs = ["*"]
    options.glyph_names = False
    options.hinting = True
    options.drop_tables += ["DSIG", "BASE", "STAT", "vhea", "vmtx"]

    subsetter = Subsetter(options=options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    rename_family(font, FAMILY, style, weight)

    output = FONT_OUT / f"mcsight-sans-w{weight}.woff2"
    font.flavor = "woff2"
    font.save(output)
    return output


def merge_family(faces: list[dict], family: str, prefix: str) -> list[tuple[int, str]]:
    """Collapse the original unicode-range slices into one file per weight."""
    from fontTools.merge import Merger

    groups: dict[int, list[Path]] = {}
    for face in faces:
        if face["family"] != family:
            continue
        groups.setdefault(face["weight"], []).append(FONT_OUT / face["src"])
    if not groups:
        raise SystemExit(f"no source slices found for {family}")

    result: list[tuple[int, str]] = []
    for weight in sorted(groups):
        sources = groups[weight]
        missing = [str(path) for path in sources if not path.is_file()]
        if missing:
            raise SystemExit(f"missing source slices for {family} {weight}: {missing}")
        font = Merger().merge([str(path) for path in sources])
        rename_family(font, family, STYLE_BY_WEIGHT[weight], weight)
        output = FONT_OUT / f"{prefix}-w{weight}.woff2"
        font.flavor = "woff2"
        font.save(output)
        print(f"  {output.name}: {output.stat().st_size / 1024:.1f} KB")
        result.append((weight, output.name))
    return result


def write_css(manrope: list[tuple[int, str]], ibm: list[tuple[int, str]]) -> None:
    header = f"""/* Generated by web-src/scripts/build-fonts.py. Do not hand-edit. */
/* {FAMILY} is a subset of Noto Sans SC (OFL); see views/config/fonts/OFL-notosanssc.txt. */
"""
    blocks = []
    for weight, _style in WEIGHTS:
        blocks.append(f"""@font-face {{
  font-family: '{FAMILY}';
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url(../assets/fonts/mcsight-sans-w{weight}.woff2) format('woff2');
}}""")
    for family, faces in (("Manrope", manrope), ("IBM Plex Mono", ibm)):
        for weight, filename in faces:
            blocks.append(f"""@font-face {{
  font-family: '{family}';
  font-style: normal;
  font-weight: {weight};
  font-display: swap;
  src: url(../assets/fonts/{filename}) format('woff2');
}}""")
    CSS_OUT.write_text(header + "\n" + "\n".join(blocks) + "\n", encoding="utf-8")


def main() -> None:
    global FONT_OUT, CSS_OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--font",
        default=os.environ.get("NOTO_SANS_SC_VF", r"C:/Windows/Fonts/NotoSansSC-VF.ttf"),
        help="Full Noto Sans SC variable font (default: %%NOTO_SANS_SC_VF%% or the Windows system path)",
    )
    parser.add_argument("--output-dir", type=Path, default=FONT_OUT)
    parser.add_argument("--css", type=Path, default=CSS_OUT)
    args = parser.parse_args()

    source = Path(args.font)
    if not source.is_file():
        raise SystemExit(
            f"source font not found: {source}\n"
            "Pass --font /path/to/NotoSansSC-VF.ttf or set NOTO_SANS_SC_VF."
        )

    FONT_OUT = args.output_dir.resolve()
    CSS_OUT = args.css.resolve()
    FONT_OUT.mkdir(parents=True, exist_ok=True)

    try:
        import brotli  # noqa: F401
    except ImportError:
        raise SystemExit("brotli is required to write WOFF2: python -m pip install brotli")

    text = charset()
    faces = parse_faces(CSS_OUT.read_text(encoding="utf-8"))
    print(f"charset: {len(text)} characters; source slices: {len(faces)}")

    total = 0
    for weight, style in WEIGHTS:
        output = build_weight(source, weight, style, text)
        size = output.stat().st_size
        total += size
        print(f"  {output.name}: {size / 1024:.1f} KB")

    manrope = merge_family(faces, "Manrope", "manrope")
    ibm = merge_family(faces, "IBM Plex Mono", "ibm-plex-mono")
    for _, filename in manrope + ibm:
        total += (FONT_OUT / filename).stat().st_size

    write_css(manrope, ibm)
    print(f"total self-hosted fonts: {total / 1024 / 1024:.2f} MB")
    print(f"css: {CSS_OUT}")


if __name__ == "__main__":
    main()
